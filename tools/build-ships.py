#!/usr/bin/env python3
"""Rebuild assets/ship-models.js from the Quaternius Ultimate Spaceships pack.

The pack is CC0 and lives outside the repo (212 MB of FBX, Blend and 2048px PNGs).
Only the OBJ text the game actually parses is embedded, with coordinates trimmed to
four decimals -- at the scale these ships are drawn, four decimals is a fraction of a
millimetre, and it takes the bundle from 2.2 MB to about half that.

    python3 tools/build-ships.py [--pack DIR]

Textures are a separate step: they are converted once by hand to 1024px JPEGs in
assets/ (see README), because the choice of colour variant per ship is a design call.
"""
import argparse
import os
import re

PACK = os.path.expanduser('~/assetpacks/quaternius-spaceships/extracted/Ultimate Spaceships - May 2021')
# Every ship the game loads, in the order the bundle lists them.
SHIPS = ['Striker', 'Dispatcher', 'Spitfire', 'Imperial', 'Pancake',
         'Executioner', 'Zenith', 'Bob', 'Challenger', 'Omen', 'Insurgent']
HEAD = ('// Quaternius Ultimate Spaceships (CC0, quaternius.com): OBJ models embedded as text so the page can load them.\n'
        '// Generated by tools/build-ships.py -- edit that, not this.\n'
        'window.__SHIP_OBJ = {\n')

num = re.compile(r'-?\d+\.\d+')


def trim(line):
    """Round the floats on a v/vn/vt line, and drop a trailing zero fraction."""
    def one(m):
        s = f'{float(m.group()):.4f}'.rstrip('0').rstrip('.')
        return s or '0'
    return num.sub(one, line)


def body(path):
    out = []
    for line in open(path):
        line = line.rstrip('\n')
        if not line or line.startswith('#') or line.startswith('mtllib') or line.startswith('usemtl'):
            continue
        out.append(trim(line) if line[0] == 'v' else line)
    return '\n'.join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--pack', default=PACK)
    ap.add_argument('--out', default=os.path.join(os.path.dirname(__file__), '..', 'assets', 'ship-models.js'))
    a = ap.parse_args()
    parts = [HEAD]
    for name in SHIPS:
        src = os.path.join(a.pack, name, 'OBJ', f'{name}.obj')
        if not os.path.exists(src):
            raise SystemExit(f'missing {src} -- point --pack at the extracted pack')
        parts.append(f'  {name}: `{body(src)}\n`,\n')
    parts.append('};\n')
    text = ''.join(parts)
    with open(a.out, 'w') as f:
        f.write(text)
    print(f'{len(SHIPS)} ships, {len(text) // 1024} KB')


if __name__ == '__main__':
    main()
